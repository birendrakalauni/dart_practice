//Restaurant Ordering System
void main() {
  int menuChoice = 3;

  switch (menuChoice) {
    case 1:
      print("Pizza");
      break;
    case 2:
      print("Burger");
      break;
    case 3:
      print("Momo");
      break;
    case 4:
      print("Chowmein");
      break;
    default:
      print("Invalid Menu Selection");
  }
}
